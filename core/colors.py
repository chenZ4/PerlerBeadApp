    def find_closest_color(self, r, g, b):
        """找到色卡中最接近的颜色（优化版）"""
        min_dist = float('inf')
        closest_index = 0

        for i, color in enumerate(self.colors):
            cr, cg, cb = color
            dist = (r - cr) ** 2 + (g - cg) ** 2 + (b - cb) ** 2
            if dist < min_dist:
                min_dist = dist
                closest_index = i

        return (self.colors[closest_index],
                self.names[closest_index],
                self.codes[closest_index],
                closest_index)

    def _rgb_to_hex(self, rgb):
        """RGB 转 HEX"""
        return '#{:02X}{:02X}{:02X}'.format(*rgb)

    @property
    def hex_codes(self):
        """动态生成 HEX 颜色码列表"""
        return [self._rgb_to_hex(rgb) for rgb in self.colors]

    def get_color_info(self, index):
        """获取单个颜色的完整信息"""
        if 0 <= index < len(self.colors):
            return {
                'code': self.codes[index].strip(),
                'name': self.names[index].strip(),
                'rgb': self.colors[index],
                'hex': self.hex_codes[index]
            }
        return None

